-- 직원 역할 나누기: '종사자' → '센터장' / '생활복지사'
--
-- 실행 순서: 위에서 아래로 통째로 실행하면 됩니다.
-- 여러 번 실행해도 안전합니다 — 옮길 행이 없으면 아무것도 안 바뀝니다.
--
-- [순서가 중요하다]
-- 옛 CHECK 가 살아 있는 채로 UPDATE 를 돌리면 '생활복지사' 가 아직 허용값이 아니라 막힌다.
-- 그래서 ① 옛 제약을 먼저 떼고 → ② 값을 옮기고 → ③ 새 제약을 건다.
-- (처음 버전은 ②를 먼저 해서 23514 로 실패했다)
--
-- [왜]
-- 종사자 안에서 시설장과 생활복지사는 하는 일이 다르고, 나중에 권한(로그인)도 갈린다.
-- 한 값으로 묶어 두면 그때 다시 나눠야 한다.
--
-- [기존 행]
-- role='종사자' 는 모두 '생활복지사' 로 옮긴다. 시설장은 화면에서 '센터장' 으로 바꾼다.
-- (이 파일은 누가 시설장인지 모른다. 코드가 사람을 골라 승격하면 안 된다.)
--
-- ['종사자' 값은 없앤다]
-- 남겨 두면 "쓰지 않는 값"이 코드 곳곳의 조건문에 계속 나타난다.
-- 옮긴 뒤에는 어느 행도 그 값이 아니므로 새 CHECK 에서 뺀다.
-- =============================================================


-- ① 옛 제약을 뗀다.
--    002 에서 이름 없이 만든 CHECK 라 Postgres 가 staff_role_check 로 이름을 붙였다.
--    다른 이름이면 아래 select 로 확인한 뒤 그 이름으로 바꿔 실행한다.
--      select conname from pg_constraint where conrelid = 'public.staff'::regclass and contype = 'c';
alter table public.staff
  drop constraint if exists staff_role_check;

-- ② 기존 종사자를 생활복지사로. 제약이 없는 사이에 옮긴다.
update public.staff
   set role = '생활복지사'
 where role = '종사자';

-- ③ 새 제약을 건다. 이제 '종사자' 인 행은 없다.
alter table public.staff
  add constraint staff_role_check
  check (role in ('멘토', '봉사자', '센터장', '생활복지사'));

comment on table public.staff is
  '명단: 직원(멘토/봉사자/센터장/생활복지사). 성인이라 신원을 분리하지 않고 한 테이블에 둔다.';


-- =============================================================
-- 확인: 역할별 인원. '종사자' 가 0 이어야 한다.
-- =============================================================
select role, count(*) from public.staff group by role order by role;
