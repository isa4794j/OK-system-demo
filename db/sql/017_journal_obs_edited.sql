-- =============================================================
-- OK-system 마이그레이션 017
-- 사람이 손댄 관찰 후보를 표시한다.
--
-- 001~016 이 먼저 실행돼 있어야 합니다. 여러 번 실행해도 안전합니다.
--
-- [무엇이 문제였나]
-- 다시 분석하면 그 일지의 후보를 지우고 새로 넣는다.
-- 이미 가져갔거나 합쳐진 후보는 남겨 두지만, 사람이 내용을 고치거나
-- 나누거나 아동을 정해 둔 후보는 그냥 지워졌다.
-- 손으로 다듬어 놓은 것이 [다시 분석] 한 번에 사라지는 셈이다.
--
-- [어떻게 바꾸나]
-- 손댄 시각을 남기고, 다시 분석할 때 그 후보는 건드리지 않는다.
-- "언제 손댔나" 까지 남기는 이유는, 나중에 "원본 일지가 그 뒤로 바뀌었는지"를
-- 견줘 볼 수 있게 하기 위해서다(observations 의 source_journal_updated_at 과 같은 생각).
-- =============================================================


-- =============================================================
-- 1. 손댄 시각
-- =============================================================
alter table public.journal_observations
  add column if not exists edited_at timestamptz;

comment on column public.journal_observations.edited_at is
  '사람이 내용을 고치거나 나누거나 아동을 정한 시각. 값이 있으면 다시 분석해도 지우지 않는다.';


-- =============================================================
-- 2. 다시 분석할 때 남길 후보를 빨리 찾기
--
-- 한 일지의 후보 중 "남겨야 하는 것"만 골라 읽는 질의가 잦다.
-- =============================================================
create index if not exists idx_journal_observations_edited
  on public.journal_observations (journal_id)
  where edited_at is not null;


-- =============================================================
-- 3. RLS — 001~016 과 같이 지금은 켜지 않는다. 새 테이블도 없다.
-- =============================================================


-- =============================================================
-- 4. 확인용 조회 (실행 후 결과 확인)
-- =============================================================
select column_name, data_type, is_nullable
from information_schema.columns
where table_schema = 'public'
  and table_name = 'journal_observations'
order by ordinal_position;
