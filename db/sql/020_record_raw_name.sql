-- =============================================================
-- OK-system 마이그레이션 020
-- 기록에 "일지에 적혀 있던 그대로의 표기"를 남긴다.
--
-- 001~019 가 먼저 실행돼 있어야 합니다. 여러 번 실행해도 안전합니다.
--
-- [왜 필요한가]
-- 자원을 뽑을 때 AI 는 사전의 별칭을 정식 이름으로 바꿔 준다.
-- 일지에 "나무탑"이라고 적혀 있어도 젠가의 별칭이면 "젠가"로 저장된다.
-- 통계를 갈라지지 않게 하는 장치인데, 그 대가로 원래 표기가 사라진다.
--
-- 그래서 별칭을 다시 떼어낼 수가 없었다. "스마트올"을 "태블릿"에서 분리해도
-- 어느 기록이 스마트올이라고 적혀 있던 것인지 알 방법이 없다.
--
-- 이 컬럼이 그 표기를 담는다. 앞으로 쌓이는 기록은 분리할 때 함께 옮길 수 있다.
--
-- [옛 기록은 옮길 수 없다]
-- 이미 쌓인 기록에는 채워 넣을 값이 없다. 넣을 수 있는 것이 없어 NULL 로 둔다.
-- 화면은 "기존 기록 N건은 원래 표기를 알 수 없어 그대로 남습니다"라고 알린다.
-- 추측해서 채우면 틀린 기록을 사실처럼 만드는 일이라, 비워 두는 편이 맞다.
-- =============================================================

alter table public.resource_records
  add column if not exists raw_name text;

comment on column public.resource_records.raw_name is
  '일지에 적혀 있던 그대로의 표기. 사전 별칭을 정식 이름으로 바꾸기 전 값이다. '
  '020 이전 기록은 NULL — 그때는 남기지 않았다. 별칭 분리가 이 값으로 기록을 찾는다.';

-- 별칭 분리가 "이 표기로 들어온 기록"을 찾을 때 쓴다
create index if not exists idx_resource_records_raw_name
  on public.resource_records (raw_name)
  where raw_name is not null;


-- =============================================================
-- 확인용 조회 (실행 후)
-- =============================================================
select
  count(*) filter (where raw_name is null) as 표기_모름,
  count(*) filter (where raw_name is not null) as 표기_있음
from public.resource_records;
