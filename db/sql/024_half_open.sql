--
-- 001~023 이 먼저 실행돼 있어야 합니다. 여러 번 실행해도 안전합니다.
-- =============================================================


-- =============================================================
-- 1. half_observation_open — 반기별 열림·닫힘
--
-- { "2026-1": false, "2026-2": true }
--
-- 반기가 끝나면 그 반기 관찰은 더 쓰지 않는 것이 맞다. 그런데 자동으로 닫으면
-- 12월 31일에 적다 만 사람이 1월 1일에 못 쓰게 된다. 언제 닫을지는 센터가 안다.
--
-- 빈 객체로 시작한다. 적혀 있지 않은 반기는 코드가 "이번 반기면 열림" 으로 읽는다 —
-- 설정을 한 번도 안 건드린 센터에서도 지금 반기는 쓸 수 있어야 한다.
-- =============================================================

insert into public.settings (key, value)
values ('half_observation_open', '{}'::jsonb)
on conflict (key) do nothing;


-- =============================================================
-- 2. volunteer_journal_scope 기본값을 '전체' 로
--
-- 023 에서는 '본인' 으로 시작했다. 좁은 쪽에서 시작해 필요하면 여는 것이
-- 반대보다 안전하다는 판단이었다.
--
-- 써 보니 봉사자끼리 그날 있었던 일을 못 읽는 편이 실제로는 더 불편했다.
-- 격주로 오는 사람이 지난주에 무슨 일이 있었는지 알 길이 없다.
-- 좁히는 길은 그대로 남는다 — PC 설정에서 센터장이 '본인' 으로 되돌릴 수 있다.
--
-- 이미 사람이 '본인' 으로 골라 둔 센터를 덮어쓰지 않도록,
-- 023 이 넣은 기본값 그대로인 경우에만 바꾼다.
-- =============================================================

update public.settings
set value = '"전체"'::jsonb
where key = 'volunteer_journal_scope'
  and value = '"본인"'::jsonb;


-- =============================================================
-- 3. 확인용 조회 (실행 후)
-- =============================================================
select key, value
from public.settings
where key in ('half_observation_items', 'half_observation_open', 'volunteer_journal_scope')
order by key;
