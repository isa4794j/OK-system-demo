/**
 * 서비스워커 — 캐시하지 않는다
 *
 * 하는 일은 둘뿐이다.
 *   1. 있어서 홈 화면에 "앱" 으로 설치될 수 있게 한다
 *   2. 옛 버전이 남긴 캐시가 있으면 지운다
 *
 * [왜 캐시하지 않나]
 * 서비스워커로 파일을 캐시하면 빨라지지만, 한 번 잘못 캐시되면 고친 화면이
 * 폰에 영영 안 온다. 홈 화면 앱은 주소창도 새로고침도 없어서 빠져나올 길이 없다 —
 * 앱을 지우고 다시 까는 수밖에 없다. 봉사자에게 그걸 시킬 수는 없다.
 * 빠른 첫 화면은 파일이 아니라 데이터 스냅샷(m/store.js)으로 얻는다.
 *
 * [fetch 를 가로채지 않는다]
 * fetch 처리기를 두지 않으면 요청은 서비스워커를 거치지 않고 그대로 네트워크로 간다.
 * "흘려보내기" 가 아니라 아예 손대지 않는 것이다 — 그쪽이 틀릴 일이 없다.
 * 설치 조건에 fetch 처리기가 필요하던 시절이 있었지만 지금 브라우저는 요구하지 않는다.
 *
 * 이 파일은 /sw.js 에 있어야 한다. 서비스워커는 제 위치 아래만 다스린다.
 */

self.addEventListener("install", () => {
  // 새 버전이 오면 기다리지 않고 바로 자리를 넘겨받는다.
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    // 이 앱은 캐시를 쓰지 않는다. 있다면 옛 것이다 — 전부 지운다.
    for (const key of await caches.keys()) await caches.delete(key);
    await self.clients.claim();
  })());
});
