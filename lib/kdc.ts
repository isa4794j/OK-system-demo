/**
 * KDC(한국십진분류) 번호를 사람이 읽는 이름으로
 *
 * 조회로 받는 것은 "813.7" 같은 번호다. 그대로 두면 서가에서 아무 도움이 안 된다.
 * 사서가 아닌 사람이 "이 책 어디 꽂지"를 판단할 수 있는 만큼만 이름을 붙인다.
 *
 * [어디까지 나누나]
 * 대분류 열 개 + 문학(800)의 나라별 갈래까지다.
 * 아동도서관 장서는 문학에 크게 몰려 있어, 800 하나로는 절반이 한 칸에 들어간다.
 * 나머지 분야는 대분류로 충분하다 — 그 아래로 더 나눠 봐야 칸만 늘고 쓰는 사람이 헷갈린다.
 *
 * [이 표가 정답이 아니다]
 * 자동으로 채우되 사람이 고칠 수 있다. 그림책은 번호가 제각각으로 붙어 있고
 * (813.8 로도 오고 아예 비어 있기도 하다), 센터마다 꽂는 자리가 다르다.
 * 원칙 6 과 같다 — 기계는 제안하고 사람이 정한다.
 *
 * 이 파일은 아무것도 import 하지 않는다. 서버(api/db)와 화면이 같은 표를 봐야 하는데,
 * 화면은 /db 를 못 부르므로 값을 API 응답에 실어 보낸다.
 */

/** 첫 자리 = 대분류. KDC 의 열 갈래다. */
const MAIN = [
  "총류",
  "철학",
  "종교",
  "사회과학",
  "자연과학",
  "기술과학",
  "예술",
  "언어",
  "문학",
  "역사",
] as const;

/**
 * 문학(8)의 둘째 자리 = 나라. 800(둘째 자리 0)은 문학 일반이라 대분류 이름을 그대로 쓴다.
 * 한국십진분류법 제6판 기준이다.
 */
const LITERATURE = [
  "문학", // 800 문학 일반·이론
  "한국문학", // 810
  "중국문학", // 820
  "일본문학", // 830
  "영미문학", // 840
  "독일문학", // 850
  "프랑스문학", // 860
  "스페인문학", // 870
  "이탈리아문학", // 880
  "기타문학", // 890
] as const;

/**
 * 고를 수 있는 이름 전부. 화면의 분류 고르기와 필터가 이 순서로 쓴다.
 * 문학 갈래는 "문학" 바로 뒤에 둔다 — 번호순이 곧 서가 순서다.
 */
export const KDC_LABELS: string[] = [
  ...MAIN.slice(0, 8),
  ...LITERATURE,
  MAIN[9],
];

/** 분류를 못 정한 책. 목록 필터에서 이 이름으로 모은다. */
export const KDC_UNSET = "미분류";

/**
 * KDC 번호를 이름으로. 못 읽으면 null 이다.
 *
 *   "813.7"  → 한국문학
 *   "808"    → 문학
 *   "375.1"  → 사회과학
 *   "4"      → 자연과학
 *   ""·"본표" → null
 *
 * 앞의 숫자만 본다. "813.7" 처럼 소수점이 붙어 오기도 하고
 * 간혹 "한국문학 813.7" 처럼 이름이 섞여 오기도 한다.
 */
export function kdcLabel(value: string | null | undefined): string | null {
  if (!value) return null;

  const digits = /(\d+)/.exec(value.trim());
  if (!digits) return null;

  const main = Number(digits[1][0]);
  if (!Number.isInteger(main) || main < 0 || main > 9) return null;

  if (main !== 8) return MAIN[main];

  // 문학은 둘째 자리까지 본다. 한 자리로만 오면(그냥 "8") 문학 일반으로 둔다.
  const second = digits[1].length > 1 ? Number(digits[1][1]) : 0;
  return LITERATURE[Number.isInteger(second) && second >= 0 && second <= 9 ? second : 0];
}
